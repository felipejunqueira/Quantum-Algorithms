"""---
# 2. Estado GHZ: Emaranhamento Multipartido (3 Qubits)

A generalização do emaranhamento para sistemas multipartidos resulta em estados como o **Estado GHZ** (Greenberger-Horne-Zeilinger):
$$|\text{GHZ}\rangle = \frac{|000\rangle + |111\rangle}{\sqrt{2}}$$

Neste estado, a medição de um único subsistema na base computacional colapsa instantaneamente os estados dos demais subsistemas para o mesmo valor lógico.
"""

# ==============================================================================
# ESTADO GHZ: Emaranhamento em Cascata com 3 Qubits
# ==============================================================================

from qiskit import QuantumCircuit, transpile
from qiskit_aer import AerSimulator
from qiskit.visualization import plot_histogram
