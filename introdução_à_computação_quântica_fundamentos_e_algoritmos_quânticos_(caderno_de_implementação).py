"""---
# 1. Estados de Bell: O Fundamento do Emaranhamento Quântico

O emaranhamento quântico descreve uma correlação não clássica entre subsistemas quânticos. Quando duas partículas estão emaranhadas, o estado global do sistema não pode ser descrito como um produto tensorial dos estados individuais, resultando em fortes correlações nas medições.

Existem 4 estados maximamente emaranhados para um sistema bipartido de qubits, conhecidos como **Estados de Bell**:
1. $|\Phi^+\rangle = \frac{|00\rangle + |11\rangle}{\sqrt{2}}$: Correlação total com fase positiva.
2. $|\Phi^-\rangle = \frac{|00\rangle - |11\rangle}{\sqrt{2}}$: Correlação total com fase relativa negativa.
3. $|\Psi^+\rangle = \frac{|01\rangle + |10\rangle}{\sqrt{2}}$: Anticorrelação total com fase positiva.
4. $|\Psi^-\rangle = \frac{|01\rangle - |10\rangle}{\sqrt{2}}$: O Estado Singleto (anticorrelação com fase negativa).
"""

# ==============================================================================
# PRIMEIRO ESTADO DE BELL: |Phi+> = (|00> + |11>) / sqrt(2)
# ==============================================================================

from qiskit import QuantumCircuit, transpile
from qiskit_aer import AerSimulator
from qiskit.visualization import plot_histogram
import matplotlib.pyplot as plt

# PASSO 1: Inicialização do circuito bipartido
circuito_bell_1 = QuantumCircuit(2, 2)

# PASSO 2: Criação de superposição no qubit de controle
circuito_bell_1.h(0)

# PASSO 3: Geração do emaranhamento via porta CNOT
circuito_bell_1.cx(0, 1)

# PASSO 4: Medição na base computacional Z
circuito_bell_1.measure([0, 1], [0, 1])

# PASSO 5: Execução da simulação
simulador = AerSimulator()
circuito_compilado = transpile(circuito_bell_1, simulador)
resultados = simulador.run(circuito_compilado, shots=1024).result().get_counts()

print("Distribuição de Probabilidades:", resultados)
print("Observação: Medições altamente correlacionadas nos estados |00> e |11>.")

display(circuito_bell_1.draw('mpl'))
display(plot_histogram(resultados, title="Primeiro Estado de Bell: |Phi+>"))

# Fonte: Nielsen, M. A., & Chuang, I. L. (2010). Quantum Computation and Quantum Information, Cap. 1, pág. 25.

# ==============================================================================
# SEGUNDO ESTADO DE BELL: |Phi-> = (|00> - |11>) / sqrt(2)
