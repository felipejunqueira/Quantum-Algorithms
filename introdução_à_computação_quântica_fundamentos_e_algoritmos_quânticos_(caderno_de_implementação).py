"""---
# 9. Algoritmo de Shor: Fatoração de Inteiros em Tempo Polinomial

A segurança de sistemas criptográficos como o RSA baseia-se na intratabilidade clássica do problema da fatoração de inteiros. O Algoritmo de Shor demonstra que um computador quântico pode resolver este problema em **tempo polinomial $\mathcal{O}(n^3)$**, reduzindo a fatoração ao problema de encontrar a periodicidade da função de exponenciação modular.

Demonstração para $N = 15$ escolhendo um valor coprimo $a = 7$:
1. A função $f(x) = 7^x \pmod{15}$ possui um período $r = 4$.
2. A sub-rotina quântica de estimação de fase (QPE) avalia a fase associada ao operador modular, determinando o período $r$.
3. Através do algoritmo clássico de Euclides, computa-se $\gcd(a^{r/2} \pm 1, N)$, obtendo-se os fatores não triviais.
"""

# ==============================================================================
# ALGORITMO DE SHOR: Fatoração Quântica do Número N = 15
# ==============================================================================

import numpy as np
import math
from fractions import Fraction
from qiskit import QuantumCircuit, transpile
from qiskit_aer import AerSimulator
from qiskit.circuit.library import UnitaryGate, QFTGate
from qiskit.visualization import plot_histogram
import matplotlib.pyplot as plt

# 1. PARÂMETROS INICIAIS DO PROBLEMA
# Queremos fatorar N. Para isso, escolhemos um número 'a' (palpite) que seja
# menor que N e coprimo a ele (MDC(a, N) = 1).
numero_para_fatorar_N = 15
palpite_coprimo_a = 7

print(f"Número que queremos fatorar: N = {numero_para_fatorar_N}")
print(f"Palpite coprimo escolhido:   a = {palpite_coprimo_a}")

def construir_matriz_relogio_modular(a, N, total_qubits):
    """Cria a matriz unitária que calcula a multiplicação modular: |i> -> |(a*i) mod N>."""
    dimensao = 2 ** total_qubits
    matriz_U = np.zeros((dimensao, dimensao))
    for i in range(dimensao):
        if i < N:
            matriz_U[(a * i) % N, i] = 1.0
        else:
            matriz_U[i, i] = 1.0
    return matriz_U

# 2. CONSTRUÇÃO DO CIRCUITO: BUSCA DE PERÍODO QUÂNTICO
# O coração do algoritmo de Shor reduz a fatoração ao problema de encontrar
# o período 'r' da função exponencial f(x) = a^x mod N.
qubits_contagem = 4 # Registrador de leitura (armazena as fases)
qubits_alvo = 4     # Registrador alvo (espaço para computar módulo 15)

circuito_shor = QuantumCircuit(qubits_contagem + qubits_alvo, qubits_contagem)

# Inicialização: Registrador de leitura em superposição para explorar múltiplos valores simultaneamente.
# Registrador alvo é inicializado em |1> (estado neutro da multiplicação).
circuito_shor.h(range(qubits_contagem))
circuito_shor.x(qubits_contagem)
circuito_shor.barrier()

# Phase Kickback (Retropropagação de fase):
# Aplicamos a multiplicação modular repetidas vezes, controladas pelos qubits de leitura.
# Isso irá codificar a informação do período nas fases do registrador de leitura.
matriz_base = construir_matriz_relogio_modular(palpite_coprimo_a, numero_para_fatorar_N, qubits_alvo)
alvos = list(range(qubits_contagem, qubits_contagem + qubits_alvo))

for q_leitura in range(qubits_contagem):
    potencia = 2 ** q_leitura
    matriz_potencia = np.linalg.matrix_power(matriz_base, potencia)
    porta_cu = UnitaryGate(matriz_potencia, label=f"U^{potencia}").control(1)
    circuito_shor.append(porta_cu, [q_leitura] + alvos)

circuito_shor.barrier()

# Transformada de Fourier Quântica Inversa (QFT†):
# Até agora, a informação do período está nas "fases" (como frequências). A QFT Inversa
# transforma essas fases em amplitudes mensuráveis, permitindo ler o valor na base clássica.
decodificador_qft = QFTGate(num_qubits=qubits_contagem).inverse()
decodificador_qft.name = "QFT†"
circuito_shor.append(decodificador_qft, range(qubits_contagem))

# Medição do registrador de leitura
circuito_shor.measure(range(qubits_contagem), range(qubits_contagem))

# 3. EXECUÇÃO NO SIMULADOR QUÂNTICO
simulador = AerSimulator()
contagens = simulador.run(transpile(circuito_shor, simulador), shots=2048).result().get_counts()

print("\nResultados Brutos da Medição Quântica:", contagens)

# 4. PÓS-PROCESSAMENTO CLÁSSICO: ENCONTRANDO E VALIDANDO O PERÍODO 'r'
# Ordenamos os estados mais medidos e descartamos o estado |0000> (fase zero não traz informação).
medicoes_ordenadas = sorted(contagens.items(), key=lambda item: item[1], reverse=True)
candidatos_nao_zero = [est for est, _ in medicoes_ordenadas if est != "0" * qubits_contagem]

# Como estados onde 's' e 'r' não são coprimos (ex: |1000>, onde s/r = 2/4 = 1/2)
# simplificam a fração e geram um subperíodo falso (r = 2), testamos os candidatos
# mais votados até encontrar aquele que satisfaz a condição do ciclo: (a^r) mod N == 1.
melhor_estado = None
for estado_candidato in candidatos_nao_zero:
    valor_decimal = int(estado_candidato, 2)
    fase_medida = valor_decimal / (2 ** qubits_contagem)

    # Convertendo a fase decimal em fração irredutível via Frações Contínuas
    fracao = Fraction(fase_medida).limit_denominator(numero_para_fatorar_N)
    r_teste = fracao.denominator

    # Validação clássica eficiente: verifica se r_teste é realmente o período da função
    if pow(palpite_coprimo_a, r_teste, numero_para_fatorar_N) == 1:
        melhor_estado = estado_candidato
        periodo_r = r_teste
        break

print(f"\nEstado Binário Validado: |{melhor_estado}> (Decimal: {valor_decimal})")
print(f"Fase Extraída pela QPE:  theta = {valor_decimal} / 16 = {fase_medida}")
print(f"Fração Contínua:         {fracao.numerator} / {periodo_r}")
print(f"Período Encontrado (r):  {periodo_r}")

# 5. CÁLCULO FINAL DOS FATORES PRIMOS
# Se o período 'r' for par e a^(r/2) não for congruente a -1 (mod N),
# podemos extrair os fatores primos usando o Máximo Divisor Comum (MDC).
if periodo_r % 2 == 0 and pow(palpite_coprimo_a, periodo_r // 2, numero_para_fatorar_N) != numero_para_fatorar_N - 1:
    termo_base = int(palpite_coprimo_a ** (periodo_r // 2))
    # Fatores são encontrados calculando o MDC(a^(r/2) ± 1, N)
    fator_1 = math.gcd(termo_base - 1, numero_para_fatorar_N)
    fator_2 = math.gcd(termo_base + 1, numero_para_fatorar_N)
    print("\n==================================================")
    print(f"NÚMERO {numero_para_fatorar_N} FATORADO COM SUCESSO!")
    print(f"Fator 1: mdc({palpite_coprimo_a}^({periodo_r}/2) - 1, {numero_para_fatorar_N}) = {fator_1}")
    print(f"Fator 2: mdc({palpite_coprimo_a}^({periodo_r}/2) + 1, {numero_para_fatorar_N}) = {fator_2}")
    print(f"Verificação: {fator_1} x {fator_2} = {fator_1 * fator_2}")
    print("==================================================")

display(circuito_shor.draw('mpl', style="iqp"))
display(plot_histogram(contagens, title="Algoritmo de Shor: Distribuição de Fases"))

