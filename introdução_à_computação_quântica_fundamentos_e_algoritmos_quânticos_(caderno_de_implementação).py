"""---
# 8. Estimação de Fase Quântica (QPE)

A **Estimação de Fase Quântica** (*Quantum Phase Estimation* - QPE) é um dos algoritmos centrais da computação quântica. Sua função é determinar o autovalor $e^{2\pi i \theta}$ associado a um autovetor de um determinado operador unitário $U$.

A precisão do algoritmo é proporcional ao número de qubits utilizados no registrador de avaliação.
1. Aplica-se sucessivamente o operador $U$ condicionado ao registrador, retropropagando a fase (*Phase Kickback*).
2. Utiliza-se a **QFT Inversa (QFT$^\dagger$)** sobre o registrador para interferir de forma construtiva no valor que codifica o ângulo $\theta$, revelando-o na medição em base computacional.
"""

# ==============================================================================
# ESTIMAÇÃO DE FASE QUÂNTICA (QPE): Avaliação de Autovalores de Operadores Unitários
# ==============================================================================

from qiskit import QuantumCircuit, transpile
from qiskit_aer import AerSimulator
from qiskit.circuit.library import QFTGate
from qiskit.visualization import plot_histogram
import numpy as np
import matplotlib.pyplot as plt

# PASSO 1: Definição da fase inerente ao operador unitário
fase_theta = 1 / 8  # 0.125
angulo_rotacao = 2 * np.pi * fase_theta

qubits_leitura = 3 # Determina a precisão da estimativa
qubit_alvo = 1

circuito_qpe = QuantumCircuit(qubits_leitura + qubit_alvo, qubits_leitura)

# Preparação do registrador de avaliação
for q in range(qubits_leitura):
    circuito_qpe.h(q)

# Preparação do autovetor correspondente no registrador alvo
circuito_qpe.x(qubits_leitura)
circuito_qpe.barrier()

# PASSO 2: Aplicação controlada do operador U (Phase Kickback)
repeticoes = 1
for q_controle in range(qubits_leitura):
    for _ in range(repeticoes):
        circuito_qpe.cp(angulo_rotacao, q_controle, qubits_leitura)
    repeticoes *= 2

circuito_qpe.barrier()

# PASSO 3: Transformada de Fourier Quântica Inversa
decodificador_qft = QFTGate(num_qubits=qubits_leitura).inverse()
decodificador_qft.name = "QFT†"
circuito_qpe.append(decodificador_qft, range(qubits_leitura))

# PASSO 4: Medição do registrador de avaliação
for q in range(qubits_leitura):
    circuito_qpe.measure(q, q)

simulador = AerSimulator()
resultados = simulador.run(transpile(circuito_qpe, simulador), shots=1024).result().get_counts()

estado_medido = max(resultados, key=resultados.get)
valor_inteiro = int(estado_medido, 2)
fase_estimada = valor_inteiro / (2 ** qubits_leitura)

print(f"Estado Dominante Medido: |{estado_medido}> (Valor: {valor_inteiro})")
print(f"Estimativa da Fase (theta): {valor_inteiro} / {2 ** qubits_leitura} = {fase_estimada}")
print(f"Valor Analítico da Fase: {fase_theta}")

display(circuito_qpe.draw('mpl', style="iqp"))
display(plot_histogram(resultados, title="QPE: Distribuição das Fases Estimadas"))

